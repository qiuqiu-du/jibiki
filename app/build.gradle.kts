// Release signing (docs/release.md): keystore.properties at the repository root (never
// committed) or, in CI, the JISHO_* environment variables. Without either, release builds
// fall back to this computer's debug key; -PrequireReleaseSigning=true makes that an error.
val signing: Map<String, String?> = run {
    val file = rootProject.file("keystore.properties")
    val props = Properties().apply { if (file.exists()) file.inputStream().use { load(it) } }
    fun value(key: String, env: String) = props.getProperty(key) ?: providers.environmentVariable(env).orNull
    mapOf(
        "storeFile" to value("storeFile", "JISHO_KEYSTORE"),
        "storePassword" to value("storePassword", "JISHO_KEYSTORE_PASSWORD"),
        "keyAlias" to value("keyAlias", "JISHO_KEY_ALIAS"),
        "keyPassword" to value("keyPassword", "JISHO_KEY_PASSWORD"),
    )
}
val hasReleaseKey = signing.values.all { !it.isNullOrBlank() }
if (!hasReleaseKey && providers.gradleProperty("requireReleaseSigning").orNull == "true") {
    throw GradleException("Release signing required but keystore.properties / JISHO_* variables are missing")
}

/**
 * Puts datapacks/core.db.zst (open data, built by tools/build_core.py) into the APK's assets;
 * the app unpacks it on first start (DataPackManager.prepareCore). Copyrighted packs never
 * go into the APK.
 */
abstract class BundleCoreTask : DefaultTask() {
    @get:InputFiles abstract val source: ConfigurableFileCollection
    @get:OutputDirectory abstract val output: DirectoryProperty

    @TaskAction
    fun run() {
        val file = source.singleFile
        if (!file.exists()) throw GradleException("${file.path} is missing: run tools/.venv/bin/python tools/build_core.py (or scripts/deploy.sh)")
        val dir = output.get().asFile
        dir.deleteRecursively(); dir.mkdirs()
        file.copyTo(File(dir, file.name))
    }
}

val bundleCore = tasks.register<BundleCoreTask>("bundleCore") {
    source.from(rootProject.file("datapacks/core.db.zst"))
}
androidComponents {
    onVariants { variant -> variant.sources.assets?.addGeneratedSourceDirectory(bundleCore, BundleCoreTask::output) }
}

// versionCode must grow for an update to install over the old APK: the commit count does.
val commitCount: Int = providers.exec { commandLine("git", "rev-list", "--count", "HEAD"); isIgnoreExitValue = true }
    .standardOutput.asText.map { it.trim().toIntOrNull() ?: 1 }.getOrElse(1)

android {
    namespace = "app.jisho"
    compileSdk = 36

    defaultConfig {
        applicationId = "app.jisho"
        minSdk = 29
        targetSdk = 36
        versionCode = providers.gradleProperty("versionCode").orNull?.toInt() ?: commitCount
        versionName = providers.gradleProperty("versionName").orNull ?: "0.1.$commitCount"
        ndk { abiFilters += "arm64-v8a" } // only the test phone's ABI, keeps the APK small
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        // CI passes the maintainer's debug key explicitly (-PdebugKeystore): where Gradle looks for
        // ~/.android/debug.keystore depends on the machine's environment, and a missing one is
        // silently replaced by a new key, whose builds can't update installed apps.
        providers.gradleProperty("debugKeystore").orNull?.let { getByName("debug").storeFile = file(it) }
        if (hasReleaseKey) create("release") {
            storeFile = rootProject.file(signing.getValue("storeFile")!!)
            storePassword = signing["storePassword"]
            keyAlias = signing["keyAlias"]
            keyPassword = signing["keyPassword"]
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.getByName(if (hasReleaseKey) "release" else "debug")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    // Already zstd-compressed; stored as is so the APK doesn't deflate it again.
    androidResources { noCompress += "zst" }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging { resources.excludes += listOf("/META-INF/{AL2.0,LGPL2.1}", "/META-INF/CONTRIBUTORS.md", "/META-INF/LICENSE.md") }
    // On-device tests reuse the JVM test vectors (search keys, ranking cases).
    sourceSets["androidTest"].resources.srcDir("src/test/resources")
    testOptions {
        unitTests.all {
            // JVM tests read the real data packs generated by tools/ (skipped if absent).
            it.systemProperty("datapacks.dir", rootProject.file("datapacks").path)
            // ...so new or missing packs rerun the tests instead of reusing the last results.
            it.inputs.files(rootProject.fileTree("datapacks") { include("*.db", "*.zst") })
                .withPropertyName("datapacks").withPathSensitivity(PathSensitivity.RELATIVE)
            it.maxHeapSize = "2g"
        }
    }
}

